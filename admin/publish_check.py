def friendly(errors, warnings, items):
    """点検結果を [{level, title, detail, id, label}] にして返す。

    items … 質問の一覧（管理用の名前から、回答の書き出しを引くため）
    """
    by_id = {i["id"]: i for i in items}

    def label(fid):
        it = by_id.get(fid)
        if not it:
            return ""
        text = (it.get("answer") or "").replace("\n", " ").strip()
        return text[:30] + ("…" if len(text) > 30 else "")

    out = []
    for kind, messages in (("stop", errors), ("note", warnings)):
        for msg in messages:
            hit = None
            for level, pattern, title, detail in RULES:
                m = re.search(pattern, msg)
                if m:
                    hit = (level, title, detail, m.groupdict())
                    break
            if hit is None:
                # 知らない文は、そのまま見せる（隠さない）
                out.append({"level": kind, "title": msg, "detail": "", "id": "", "label": ""})
                continue
            level, title, detail, g = hit
            fid = g.get("id", "")
            # 読み上げ用の短い回答がすでにあるなら、長さの注意は出さない
            # （build_faq.py はその列を見ないため、ここで外す）
            if title.startswith("回答が長い") and (by_id.get(fid) or {}).get("short"):
                continue
            out.append({"level": level, "title": title,
                        "detail": detail.format(**{k: v or "" for k, v in g.items()}),
                        "id": fid, "label": label(fid)})
    return out
